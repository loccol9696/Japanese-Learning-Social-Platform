-- Thông báo tương tác (bình luận, thích, chia sẻ) và thông báo hệ thống (duyệt / từ chối video).
-- Chạy tay trên môi trường dùng ddl-auto=validate (prod). Môi trường dev (ddl-auto=update) tự
-- tạo bảng. CHECK notifications_type_check do NotificationSchemaUpdater gỡ lúc khởi động.
CREATE TABLE IF NOT EXISTS notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id bigint NOT NULL,
    actor_id bigint,
    type varchar(30) NOT NULL,
    video_id bigint,
    comment_id bigint,
    detail text,
    dedupe_key varchar(100),
    read_at timestamp(6),
    created_at timestamp(6) NOT NULL,
    CONSTRAINT uk_notifications_dedupe UNIQUE (recipient_id, dedupe_key)
);
CREATE INDEX IF NOT EXISTS idx_notifications_recipient_created ON notifications (recipient_id, created_at);
CREATE INDEX IF NOT EXISTS idx_notifications_comment ON notifications (comment_id);
